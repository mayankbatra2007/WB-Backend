// What is REST?
// REST stands for Representational State Transfer.

// REST is an architectural style used to design APIs that allow the frontend and backend to communicate through HTTP.

// What is a resource?
// A resource is an object or entity that your application manages.

// Examples:
// - posts
// - users
// - products
// - orders
// - students

// REST URL examples
// URL	Resource
// /posts	All posts
// /posts/101	Post with ID 101
// /users	All users
// /users/5	User with ID 5

// REST uses HTTP methods
// HTTP Method	Purpose
// GET	Read data
// POST	Create data
// PUT	Replace data
// PATCH	Update part of data
// DELETE	Delete data

// Remember
// REST = Resources + URLs + HTTP Methods