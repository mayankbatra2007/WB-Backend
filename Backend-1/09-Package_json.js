
// 09 - PACKAGE.JSON


// package.json is the configuration file of a
// Node.js project.

// It stores important project information.

// Contains:
// - Project name and version
// - Dependencies
// - Development dependencies
// - Scripts
// - Project metadata

// Create package.json:
// npm init

// Create with default settings:
// npm init -y

// Example script:
// "scripts": {
//     "start": "node app.js"
// }

// Run script:
// npm start