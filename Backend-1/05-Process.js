// 06 - PROCESS IN NODE

// process is abuilt in global object in Node.js

// It provides Info and control over
// the current Node.js exec process

// IMP Properties and Methods
process.version; // Node.js version
process.platform; // Operating System
process.cwd(); // current working directory
process.argv; // Command-line args : eg -> node app.js neha aman etc -> theses names are args
process.exit(); // Terminates Process